const commentEl = document.getElementById("comment");
const generateBtn = document.getElementById("generateBtn");
const copyBtn = document.getElementById("copyBtn");
const statusEl = document.getElementById("status");

let currentComment = "";
let lastType = null;
let lastPattern = null;
const recentTexts = [];
const RECENT_LIMIT = 20;

function pickComment() {
  let pool = comments.filter(item =>
    item.type !== lastType &&
    item.pattern !== lastPattern &&
    !recentTexts.includes(item.text)
  );

  if (!pool.length) {
    pool = comments.filter(item =>
      item.pattern !== lastPattern &&
      !recentTexts.includes(item.text)
    );
  }

  if (!pool.length) {
    pool = comments.filter(item => !recentTexts.includes(item.text));
  }

  if (!pool.length) {
    recentTexts.length = 0;
    pool = comments;
  }

  return pool[Math.floor(Math.random() * pool.length)];
}

generateBtn.addEventListener("click", () => {
  if (!comments.length) return;
  const picked = pickComment();
  currentComment = picked.text;
  lastType = picked.type;
  lastPattern = picked.pattern;
  recentTexts.push(picked.text);
  if (recentTexts.length > RECENT_LIMIT) recentTexts.shift();
  commentEl.textContent = currentComment;
  copyBtn.disabled = false;
  statusEl.textContent = "";
});

copyBtn.addEventListener("click", async () => {
  if (!currentComment) return;
  try {
    await navigator.clipboard.writeText(currentComment);
    statusEl.textContent = "COPIED ♡";
    setTimeout(() => statusEl.textContent = "", 1300);
  } catch {
    statusEl.textContent = "COPY FAILED";
  }
});
